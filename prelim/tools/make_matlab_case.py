"""
Generate matlab/cosserat_case.m from the user's cosserat_yeoh_quasistatic.m.

The solver is copied unchanged (sections 1-4 + all local functions); only the
plots/exports are dropped and these lines become overridable by the caller:
    robot.basePosition    <- CASE_P   (if defined)
    robot.baseQuaternion  <- CASE_Q   (if defined, [w x y z])
    sec(1:2)              <- makeSection(..., CASE_SEC(j,:) = [r offset chamberR], ...)
                                      (if defined, [m]; same material)
    sec(1:2).L            <- CASE_L   (if defined, [m])
    pTarget{1:2}          <- pressureFromBend(sec(j), CASE_BEND(j,1), CASE_BEND(j,2))
                                      (if defined, radians)
    loadData.gravity      <- CASE_G
    loadData.tipForce     <- CASE_F
and the final centreline is written to CASE_OUT.

Run:  python3 tools/make_matlab_case.py ~/Documents/MATLAB/cosserat_yeoh_quasistatic.m matlab/cosserat_case.m
"""
import sys

src_path, out_path = sys.argv[1], sys.argv[2]
src = open(src_path).read().split('\n')
plots = next(i for i, l in enumerate(src) if l.startswith('%% 5) Plots'))
funcs = next(i for i, l in enumerate(src) if l.startswith('%% Local functions'))

body = []
for line in src[:plots]:
    if line.startswith('clear; clc'):
        continue
    if line.startswith('robot.basePosition'):
        line += "\nif exist('CASE_P','var'), robot.basePosition = CASE_P(:); end"
    elif line.startswith('robot.baseQuaternion'):
        line += "\nif exist('CASE_Q','var'), robot.baseQuaternion = CASE_Q(:); end"
    elif line.startswith('sec(2) = makeSection('):
        # section lengths only enter through sec(j).L (the Yeoh M(k) table is per area)
        # CASE_SEC = [radius offset chamberRadius] per row [m]: rebuild the section
        # (same material, density, chamber count) with the new cross-section
        line += ("\nif exist('CASE_SEC','var'), for jj = 1:2, sec(jj) = makeSection(sec(jj).L, "
                 "CASE_SEC(jj,1), sec(jj).yeoh, sec(jj).rho, CASE_SEC(jj,2), CASE_SEC(jj,3), "
                 "size(sec(jj).d,2)); end, end")
        line += "\nif exist('CASE_L','var'), sec(1).L = CASE_L(1); sec(2).L = CASE_L(2); end"
    elif line.startswith('pTarget{2} = pressureFromBend('):
        # CASE_BEND = [bend1 plane1; bend2 plane2] in radians
        line += ("\nif exist('CASE_BEND','var'), for jj = 1:2, "
                 "pTarget{jj} = pressureFromBend(sec(jj), CASE_BEND(jj,1), CASE_BEND(jj,2)); end, end")
    elif line.startswith('loadData.gravity'):
        line = 'loadData.gravity = CASE_G(:);'
    elif line.startswith('loadData.tipForce'):
        line = 'loadData.tipForce = CASE_F(:);'
    body.append(line)

header = ['% GENERATED by tools/make_matlab_case.py from cosserat_yeoh_quasistatic.m.',
          '% Solver unchanged; base pose and loads come from CASE_* variables (see run_cases.m).',
          '']
footer = ["writematrix(solution.r.', CASE_OUT);",
          "fprintf('CASE %s tip [mm] = [%8.2f %8.2f %8.2f]\\n', CASE_OUT, 1e3*solution.r(:,end));",
          '']
open(out_path, 'w').write('\n'.join(header + body + footer + src[funcs:]))
print('wrote', out_path)
